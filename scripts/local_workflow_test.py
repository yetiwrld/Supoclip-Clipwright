#!/usr/bin/env python3
"""Local workflow integration test: import -> transcribe -> analyse -> edit ->
render -> export -> save -> reload.

This runs the real code paths, not mocks, and reports what it could not run
instead of pretending:

* **Source media**: always real. If ``--source`` is not given, a real 40 s
  1280x720 MP4 with an audio tone is generated by FFmpeg.
* **Transcription**: real Whisper when the ``whisper`` package and the
  configured ``.pt`` checkpoint are present; otherwise SKIPPED with the reason.
* **Analysis / clip selection**: a real call to the configured Ollama model when
  the daemon answers on the configured base URL; otherwise SKIPPED.
* **Editing / rendering / export**: always real. The clip is cut with FFmpeg and
  exported through the application's own ``render_document`` path with burned-in
  ASS captions.
* **Save / reopen**: the edit document is written with the application's
  ``save_document`` helper and reloaded in a *fresh interpreter*, which is what a
  restart does to it. The rendered export is then verified with FFprobe.

Exit code 0 means every stage that could run passed. A skipped stage is printed
as SKIPPED with the exact missing dependency, never as a pass.

Usage (inside the backend container, or on the host with the backend venv)::

    python scripts/local_workflow_test.py
    python scripts/local_workflow_test.py --source D:\\videos\\talk.mp4 --keep

Then verify offline behaviour by repeating it with the network blocked.
"""

from __future__ import annotations

import argparse
import json
import os
import shutil
import subprocess
import sys
import time
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
BACKEND = REPO_ROOT / "backend"
if str(BACKEND) not in sys.path:
    sys.path.insert(0, str(BACKEND))

PASS, FAIL, SKIP = "PASS", "FAIL", "SKIP"
results: list[tuple[str, str, str]] = []


def record(stage: str, status: str, detail: str) -> None:
    results.append((stage, status, detail))
    color = {PASS: "\033[32m", FAIL: "\033[31m", SKIP: "\033[33m"}[status]
    print(f"  [{color}{status}\033[0m] {stage:<28} {detail}")


def run(command: list[str], **kwargs) -> subprocess.CompletedProcess:
    return subprocess.run(command, capture_output=True, text=True, check=False, **kwargs)


def probe(path: Path) -> dict:
    """Real FFprobe read of a media file."""
    result = run(
        [
            "ffprobe", "-v", "error", "-show_entries",
            "format=duration,size:stream=codec_type,codec_name,width,height,duration",
            "-of", "json", str(path),
        ]
    )
    if result.returncode != 0:
        raise RuntimeError(f"ffprobe failed on {path}: {result.stderr.strip()}")
    return json.loads(result.stdout)


def build_source(target: Path, seconds: int = 40) -> None:
    """A real 1280x720/30fps H.264 + AAC file with a moving pattern and a tone."""
    result = run(
        [
            "ffmpeg", "-v", "error", "-y",
            "-f", "lavfi", "-i", f"testsrc2=size=1280x720:rate=30:duration={seconds}",
            "-f", "lavfi", "-i", f"sine=frequency=330:duration={seconds}",
            "-c:v", "libx264", "-preset", "veryfast", "-pix_fmt", "yuv420p",
            "-c:a", "aac", "-shortest", str(target),
        ]
    )
    if result.returncode != 0:
        raise RuntimeError(f"could not build the test source: {result.stderr.strip()}")


def transcribe(source: Path) -> tuple[bool, list[dict], str]:
    """Real Whisper, or (False, [], reason)."""
    from src.config import get_config
    from src import local_ai

    config = get_config()
    try:
        import whisper  # noqa: F401  (import inside so the failure is reportable)
    except Exception as exc:  # ImportError, or torch missing
        return False, [], f"the 'whisper' package is not installed ({exc.__class__.__name__})"

    try:
        checkpoint = local_ai.ensure_whisper_model(config)
    except local_ai.LocalModelUnavailable as exc:
        return False, [], str(exc)

    started = time.perf_counter()
    model = whisper.load_model(str(checkpoint), device=config.whisper_device)
    transcript = model.transcribe(str(source), word_timestamps=True)
    elapsed = time.perf_counter() - started

    words = [
        {
            "id": f"w{index}",
            "start": round(word["start"], 3),
            "end": round(word["end"], 3),
            "text": word["word"].strip(),
        }
        for index, segment in enumerate(transcript.get("segments", []))
        for word in segment.get("words", [])
        if word.get("word", "").strip()
    ]
    print(f"       whisper: {elapsed:.1f}s for {len(words)} words "
          f"(model {config.whisper_model}, device {config.whisper_device})")
    return bool(words), words, f"{len(words)} words in {elapsed:.1f}s with {config.whisper_model}"


def analyse(words: list[dict]) -> tuple[bool, dict | None, str]:
    """Real Ollama call, or (False, None, reason)."""
    from src import local_ai
    from src.config import get_config

    config = get_config()
    status = local_ai.llm_status(config)
    if not status.get("reachable"):
        return False, None, status.get("message") or "Ollama is not reachable"
    if not status.get("model_available"):
        return False, None, status.get("message") or "the configured model is not installed"

    import httpx

    base = local_ai.native_ollama_base_url(config)
    prompt = (
        "You are helping a video editor. From this transcript excerpt, return JSON "
        '{"clips":[{"start":<s>,"end":<s>,"title":"...","reason":"..."}]} with at most 2 clips '
        "between 15 and 30 seconds long.\n\n"
+ " ".join(f"[{word['start']:.1f}-{word['end']:.1f}] {word['text']}" for word in words[:400])
    )
    started = time.perf_counter()
    try:
        response = httpx.post(
            f"{base}/api/chat",
            json={
                "model": status["model"],
                "messages": [{"role": "user", "content": prompt}],
                "stream": False,
                "options": {"num_ctx": 8192, "num_predict": 1024},
            },
            timeout=240,
        )
        response.raise_for_status()
        payload = response.json()
    except Exception as exc:
        return False, None, f"Ollama call failed: {exc.__class__.__name__}: {exc}"
    elapsed = time.perf_counter() - started

    content = (payload.get("message") or {}).get("content", "")
    start = content.find("{")
    end = content.rfind("}")
    if start == -1 or end == -1:
        return False, None, "the model did not return JSON"
    try:
        parsed = json.loads(content[start : end + 1])
    except ValueError as exc:
        return False, None, f"the model returned unparseable JSON: {exc}"
    clips = parsed.get("clips") or []
    print(f"       ollama: {elapsed:.1f}s, {len(clips)} clip(s) proposed")
    return bool(clips), {"clips": clips, "elapsed": elapsed}, f"{len(clips)} clip(s) in {elapsed:.1f}s"


def cut_clip(source: Path, target: Path, start: float, end: float) -> float:
    started = time.perf_counter()
    result = run(
        [
            "ffmpeg", "-v", "error", "-y", "-ss", f"{start:.3f}", "-to", f"{end:.3f}",
            "-i", str(source), "-c:v", "libx264", "-preset", "veryfast",
            "-pix_fmt", "yuv420p", "-c:a", "aac", str(target),
        ]
    )
    if result.returncode != 0:
        raise RuntimeError(f"cut failed: {result.stderr.strip()}")
    return time.perf_counter() - started


def synthetic_words(start: float, end: float) -> list[dict]:
    """Deterministic caption words for the render test when Whisper is skipped.

    Explicitly labelled in the report: this exercises the caption renderer, it is
    not a transcription result.
    """
    text = "ClipWright Studio renders captions locally with FFmpeg".split()
    words = []
    span = (end - start) / max(1, len(text))
    for index, token in enumerate(text):
        words.append(
            {
                "id": f"s{index}",
                "start": round(start + index * span, 3),
                "end": round(start + (index + 1) * span, 3),
                "text": token,
            }
        )
    return words


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--source", help="real media file to use; generated when omitted")
    parser.add_argument("--keep", action="store_true", help="keep the working directory")
    parser.add_argument("--workdir", help="working directory (default: a temp dir)")
    args = parser.parse_args(argv)

    import tempfile

    workdir = Path(args.workdir) if args.workdir else Path(tempfile.mkdtemp(prefix="clipwright-workflow-"))
    workdir.mkdir(parents=True, exist_ok=True)

    print("\nClipWright Studio — local workflow integration test")
    print(f"Work directory: {workdir}")
    print(f"Offline mode: {os.getenv('OFFLINE_MODE', 'unset')}   "
          f"LLM: {os.getenv('LLM', 'unset')}   Whisper: {os.getenv('WHISPER_MODEL_SIZE', 'unset')}")
    print()

    try:
        # --- 0. tools -------------------------------------------------------
        missing = [tool for tool in ("ffmpeg", "ffprobe") if not shutil.which(tool)]
        if missing:
            record("tools", FAIL, f"missing from PATH: {', '.join(missing)}")
            return 1
        version = run(["ffmpeg", "-version"]).stdout.splitlines()[0]
        record("tools", PASS, version)

        # --- 1. import a real local video -----------------------------------
        if args.source:
            source = Path(args.source).expanduser().resolve()
            if not source.is_file():
                record("import", FAIL, f"{source} does not exist")
                return 1
        else:
            source = workdir / "source.mp4"
            build_source(source)
        info = probe(source)
        video = next(s for s in info["streams"] if s["codec_type"] == "video")
        duration = float(info["format"]["duration"])
        record(
            "import local video", PASS,
            f"{source.name} {video['width']}x{video['height']} {video['codec_name']} "
            f"{duration:.1f}s {int(info['format']['size']) // 1024} KB",
        )

        # --- 2. transcription ----------------------------------------------
        whisper_ok, words, whisper_detail = transcribe(source)
        record("transcribe (Whisper)", PASS if whisper_ok else SKIP, whisper_detail)
        transcript_source = "whisper"
        if not whisper_ok:
            transcript_source = "synthetic"

        # --- 3. analysis / clip selection ----------------------------------
        analysis_ok, analysis, analysis_detail = analyse(words) if whisper_ok else (
            False, None, "no transcript from Whisper to analyse",
        )
        record("analyse (Ollama)", PASS if analysis_ok else SKIP, analysis_detail)

        if analysis_ok and analysis and analysis.get("clips"):
            clip = analysis["clips"][0]
            start = max(0.0, min(float(clip.get("start", 0)), duration - 1))
            end = max(start + 2, min(float(clip.get("end", start + 20)), duration))
            title = str(clip.get("title") or "Clip")
        else:
            title = "Clip"
            seg_len = min(20.0, max(6.0, duration - 1))
            start, end = 2.0 if duration > seg_len + 2 else 0.0, None
            end = end or min(start + seg_len, duration)
            if transcript_source == "synthetic":
                record("clip selection", SKIP,
                       f"synthetic demo window {start:.1f}-{end:.1f}s (no local models available)")
        if start >= end:
            end = min(duration, start + 6)
        if analysis_ok:
            record("clip selection", PASS, f'"{title}" {start:.1f}-{end:.1f}s ({end - start:.1f}s)')

        # --- 4. cut the clip (real ffmpeg) ---------------------------------
        clean = workdir / "clean.mp4"
        cut_seconds = cut_clip(source, clean, start, end)
        clean_info = probe(clean)
        record("cut clip", PASS,
               f"clean.mp4 {float(clean_info['format']['duration']):.2f}s in {cut_seconds:.2f}s")

        # --- 5. editor document + captions ---------------------------------
        from src.editor_document import EditDocument, render_document, save_document

        clip_duration = end - start
        caption_words = (
            [
                {**word, "start": round(word["start"] - start, 3), "end": round(word["end"] - start, 3)}
                for word in words
                if word["start"] >= start and word["end"] <= end
            ]
            if whisper_ok else synthetic_words(0.0, clip_duration)
        )
        caption_words = [
            {**word, "id": f"c{index}", "start": max(0.0, word["start"]), "end": min(clip_duration, word["end"])}
            for index, word in enumerate(caption_words)
            if word["end"] > 0 and word["start"] < clip_duration
        ]
        document = EditDocument.model_validate(
            {
                "segments": [{"id": "s0", "start": 0.0, "end": round(clip_duration, 3)}],
                "words": caption_words,
                "captions": {"enabled": bool(caption_words)},
                "framing": {"aspect": "vertical", "fit": "cover"},
                "hookTitle": title[:60],
            }
        )
        saved = save_document(workdir, document, 0, round(clip_duration, 3))
        draft_path = workdir / "draft.json"
        record("open in editor", PASS,
               f"{len(document.segments)} segment(s), {len(document.words)} caption word(s), "
               f"saved revision {saved['revision']} to {draft_path.name}")

        # --- 6. render + export (real) -------------------------------------
        started = time.perf_counter()
        render_document(workdir, "workflow-export", document, "tiktok", {})
        render_seconds = time.perf_counter() - started
        export = workdir / "export-workflow-export.mp4"
        if not export.is_file():
            record("render/export", FAIL, f"no output at {export}")
            return 1
        exported = probe(export)
        exported_video = next(s for s in exported["streams"] if s["codec_type"] == "video")
        record(
            "render/export", PASS,
            f"{export.name} {exported_video['width']}x{exported_video['height']} "
            f"{float(exported['format']['duration']):.2f}s "
            f"{int(exported['format']['size']) // 1024} KB in {render_seconds:.2f}s",
        )

        # --- 7. save + reopen in a fresh process ---------------------------
        reopened = workdir / "reopened.json"
        reopen = run(
            [
                sys.executable, "-c",
                "import json,sys;"
                f"sys.path.insert(0, {str(BACKEND)!r});"
                "from pathlib import Path;"
                "from src.editor_document import EditDocument;"
                f"payload = json.loads(Path({str(draft_path)!r}).read_text());"
                "doc = EditDocument.model_validate(payload['document']);"
                f"Path({str(reopened)!r}).write_text(json.dumps({{"
                "'revision': payload['revision'], 'segments': len(doc.segments), "
                "'words': len(doc.words), 'aspect': doc.framing.aspect, 'hook': doc.hookTitle}))",
            ]
        )
        if reopen.returncode != 0:
            record("save + reopen", FAIL, reopen.stderr.strip().splitlines()[-1] if reopen.stderr else "reload failed")
        else:
            payload = json.loads(reopened.read_text())
            matches = (
                payload["segments"] == len(document.segments)
                and payload["words"] == len(document.words)
                and payload["aspect"] == document.framing.aspect
            )
            record(
                "save + reopen", PASS if matches else FAIL,
                f"reloaded in a new process: {payload['segments']} segment(s), "
                f"{payload['words']} word(s), aspect {payload['aspect']}",
            )

        # --- 8. offline-mode guard -----------------------------------------
        from src import local_ai
        from src.config import get_config

        config = get_config()
        record(
            "offline mode", PASS if config.offline_mode else FAIL,
            f"{'on' if config.offline_mode else 'OFF'} ({config.offline_mode_source}); "
            f"hosted AI {'refused' if not config.hosted_ai_enabled else 'ALLOWED'}; "
            f"ollama {config.resolve_ollama_base_url()}",
        )

    except Exception as exc:  # noqa: BLE001 - the report needs the stage
        record("workflow", FAIL, f"{exc.__class__.__name__}: {exc}")
        import traceback

        traceback.print_exc()
    finally:
        passed = sum(1 for _, status, _ in results if status == PASS)
        failed = sum(1 for _, status, _ in results if status == FAIL)
        skipped = sum(1 for _, status, _ in results if status == SKIP)
        print()
        print("=" * 78)
        print(f"RESULT: {passed} passed, {failed} failed, {skipped} skipped")
        if skipped:
            skipped_names = ", ".join(stage for stage, status, _ in results if status == SKIP)
            print(f"NOT TESTED HERE: {skipped_names}")
            print("These stages need the real models (Whisper checkpoint, Ollama).")
            print("Run the same command inside the stack: "
                  "docker compose exec -T backend .venv/bin/python scripts/local_workflow_test.py")
        if not args.keep:
            shutil.rmtree(workdir, ignore_errors=True)
        else:
            print(f"Artifacts kept in {workdir}")

    return 1 if any(status == FAIL for _, status, _ in results) else 0


if __name__ == "__main__":
    raise SystemExit(main())
